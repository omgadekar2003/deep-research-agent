def render_pdf(question: str, markdown_text: str) -> bytes:
    """Returns PDF bytes for the given markdown report."""
    if PDF_BACKEND == "weasyprint":
        return _render_with_weasyprint(question, markdown_text)
    # elif PDF_BACKEND == "fpdf2":
    #     return _render_with_fpdf2(question, markdown_text)
    elif PDF_BACKEND == "reportlab":
        return _render_with_reportlab(question, markdown_text)
    else:
        raise ValueError(f"Unknown PDF_BACKEND: {PDF_BACKEND}")