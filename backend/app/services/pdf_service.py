def _strip_markdown_artifacts(md: str) -> str:
    """Clean up odd whitespace without breaking formatting."""
    md = re.sub(r"\n{3,}", "\n\n", md)
    return md.strip()


# ---------------------------------------------------------------------------
# weasyprint backend
# ---------------------------------------------------------------------------
def _render_with_weasyprint(question: str, markdown_text: str) -> bytes:
    import markdown as md_lib
    from weasyprint import HTML

    body_html = md_lib.markdown(
        _strip_markdown_artifacts(markdown_text),
        extensions=["extra", "tables", "fenced_code", "sane_lists"],
    )

    meta = (
        f'<div class="meta">'
        f"<strong>Research question:</strong> {question}<br>"
        f"<strong>Generated:</strong> {datetime.now().strftime('%Y-%m-%d %H:%M')}"
        f"</div>"
    )

    full_html = HTML_TEMPLATE.format(
        content=meta + body_html,
        date=datetime.now().strftime("%Y-%m-%d"),
    )

    pdf_bytes = HTML(string=full_html).write_pdf()
    return pdf_bytes


