def _render_with_reportlab(question: str, markdown_text: str) -> bytes:
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
    from reportlab.lib.units import mm
    from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, ListFlowable, ListItem, PageBreak
    from reportlab.lib.enums import TA_LEFT
    from io import BytesIO
    import re

    buffer = BytesIO()
    doc = SimpleDocTemplate(buffer, pagesize=A4, rightMargin=20*mm, leftMargin=20*mm, topMargin=20*mm, bottomMargin=20*mm)
    styles = getSampleStyleSheet()
    
    # Custom styles
    styles.add(ParagraphStyle(name='CustomH1', parent=styles['Heading1'], fontSize=20, spaceAfter=10))
    styles.add(ParagraphStyle(name='CustomH2', parent=styles['Heading2'], fontSize=15, spaceAfter=8))
    styles.add(ParagraphStyle(name='CustomH3', parent=styles['Heading3'], fontSize=12, spaceAfter=6))
    styles.add(ParagraphStyle(name='CustomBody', parent=styles['Normal'], fontSize=10, leading=14, spaceAfter=6))
    styles.add(ParagraphStyle(name='CustomQuote', parent=styles['Normal'], fontSize=9, leading=13, leftIndent=15, textColor='#555555', fontName='Helvetica-Oblique'))

    story = []
    
    # Title
    story.append(Paragraph("Deep Research Report", styles['CustomH1']))
    story.append(Spacer(1, 4*mm))
    story.append(Paragraph(f"<b>Question:</b> {question}", styles['CustomBody']))
    story.append(Paragraph(f"<i>Generated: {datetime.now().strftime('%Y-%m-%d %H:%M')}</i>", styles['CustomBody']))
    story.append(Spacer(1, 8*mm))

    # Basic Markdown parser (line-by-line)
    lines = _strip_markdown_artifacts(markdown_text).split('\n')
    i = 0
    while i < len(lines):
        line = lines[i].rstrip()
        if not line:
            i += 1
            continue
        
        # Headings
        if line.startswith('### '):
            story.append(Paragraph(line[4:], styles['CustomH3']))
        elif line.startswith('## '):
            story.append(Paragraph(line[3:], styles['CustomH2']))
        elif line.startswith('# '):
            story.append(Paragraph(line[2:], styles['CustomH1']))
        # Blockquote
        elif line.startswith('> '):
            story.append(Paragraph(line[2:], styles['CustomQuote']))
        # List items (collect consecutive bullets)
        elif line.startswith('- ') or line.startswith('* '):
            bullets = []
            while i < len(lines) and (lines[i].startswith('- ') or lines[i].startswith('* ')):
                bullets.append(ListItem(Paragraph(lines[i][2:], styles['CustomBody'])))
                i += 1
            story.append(ListFlowable(bullets, bulletType='bullet', start='•'))
            continue # already incremented
        # Numbered list
        elif re.match(r'^\d+\.\s', line):
            nums = []
            while i < len(lines) and re.match(r'^\d+\.\s', lines[i]):
                text = re.sub(r'^\d+\.\s', '', lines[i])
                nums.append(ListItem(Paragraph(text, styles['CustomBody'])))
                i += 1
            story.append(ListFlowable(nums, bulletType='1'))
            continue
        # Regular paragraph
        else:
            story.append(Paragraph(line, styles['CustomBody']))
        
        i += 1

    doc.build(story)
    return buffer.getvalue()


